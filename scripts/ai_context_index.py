#!/usr/bin/env python3
"""Generate and verify the repository's deterministic AI context catalogue.

The catalogue is derived from Git-tracked Markdown files. It is navigation and
integrity metadata only; it does not establish authority, approval or status.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / ".ai" / "CONTEXT_MANIFEST.json"
INDEX = ROOT / ".ai" / "index.md"
EXCLUDED = {".ai/index.md"}


def tracked_markdown() -> list[Path]:
    result = subprocess.run(
        ["git", "ls-files", "-z", "--", "*.md"],
        cwd=ROOT, check=True, capture_output=True,
    )
    paths = [ROOT / item.decode("utf-8") for item in result.stdout.split(b"\0") if item]
    return sorted(p for p in paths if p.relative_to(ROOT).as_posix() not in EXCLUDED)


def category(path: Path) -> str:
    parts = path.relative_to(ROOT).parts
    if parts[0] == ".ai":
        return parts[1] if len(parts) > 2 else "ai-entry"
    if len(parts) == 1:
        return "repository-entry"
    return parts[0]


def blob_sha(path: Path) -> str:
    result = subprocess.run(
        ["git", "hash-object", str(path.relative_to(ROOT))],
        cwd=ROOT, check=True, capture_output=True, text=True,
    )
    return result.stdout.strip()


def build() -> tuple[str, str]:
    entries = []
    for path in tracked_markdown():
        raw = path.read_bytes()
        rel = path.relative_to(ROOT).as_posix()
        entries.append({
            "path": rel,
            "category": category(path),
            "git_blob_sha": blob_sha(path),
            "size_bytes": len(raw),
            "content_state": "empty" if not raw.strip() else "populated",
        })

    manifest = {
        "schema_version": 1,
        "purpose": "Navigation and content-integrity metadata; not an authority or approval register.",
        "generation": "python scripts/ai_context_index.py",
        "tracked_markdown_count": len(entries),
        "empty_markdown_count": sum(e["content_state"] == "empty" for e in entries),
        "entries": entries,
    }
    manifest_text = json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"

    groups: dict[str, list[dict[str, object]]] = {}
    for entry in entries:
        groups.setdefault(str(entry["category"]), []).append(entry)
    lines = [
        "# Generated repository context index",
        "",
        "> Generated by `python scripts/ai_context_index.py`. Do not edit by hand.",
        "> This index is navigation only. Authority remains with the relevant source documents and approval register.",
        "",
        f"- Tracked Markdown documents: **{len(entries)}**",
        f"- Empty tracked Markdown placeholders: **{manifest['empty_markdown_count']}**",
        "- Integrity metadata: [CONTEXT_MANIFEST.json](CONTEXT_MANIFEST.json)",
        "- Rebuild/check: `python scripts/ai_context_index.py` / `python scripts/ai_context_index.py --check`",
        "",
    ]
    for name in sorted(groups):
        lines.extend([f"## {name}", ""])
        for entry in groups[name]:
            state = " — **EMPTY PLACEHOLDER**" if entry["content_state"] == "empty" else ""
            lines.append(f"- [`{entry['path']}`](../{entry['path']}){state}")
        lines.append("")
    return manifest_text, "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale or missing")
    args = parser.parse_args()
    manifest_text, index_text = build()
    expected = ((MANIFEST, manifest_text), (INDEX, index_text))
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, content in expected
                 if not path.exists() or path.read_text(encoding="utf-8") != content]
        if stale:
            print("AI context catalogue is stale or missing: " + ", ".join(stale), file=sys.stderr)
            print("Run: python scripts/ai_context_index.py", file=sys.stderr)
            return 1
        print("AI context catalogue check passed.")
        return 0
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(manifest_text, encoding="utf-8")
    INDEX.write_text(index_text, encoding="utf-8")
    print(f"Generated {MANIFEST.relative_to(ROOT)} and {INDEX.relative_to(ROOT)}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
